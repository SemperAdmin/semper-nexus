#!/usr/bin/env node

/**
 * Fetch DD Forms from the WHS Directives Division
 *
 * Scrapes the seven DD Forms listing pages and generates a static JavaScript
 * data file for the application, so the DD FORMS tab renders with no network
 * call.
 *
 * Source: https://www.esd.whs.mil/Directives/forms/ (seven number ranges)
 * Target: lib/dd-forms-data.js
 *
 * WHY STATIC. Same reason as scripts/fetch-dodi.mjs: the browser fetch is
 * blocked by CORS, the Render proxy's domain allowlist excludes esd.whs.mil,
 * and Akamai answers 403 to datacenter ranges. Fetch from a workstation,
 * commit the result.
 *
 *   npm run fetch-dd-forms
 *
 * Never writes an empty or sharply smaller file. A failed scrape leaves the
 * committed data in place and exits non-zero.
 */

import { readFile, writeFile } from 'fs/promises';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

export const SOURCE_URL = 'https://www.esd.whs.mil/Directives/forms/';
export const PAGE_URLS = [
  'https://www.esd.whs.mil/Directives/forms/dd0001_0499/',
  'https://www.esd.whs.mil/Directives/forms/dd0500_0999/',
  'https://www.esd.whs.mil/Directives/forms/dd1000_1499/',
  'https://www.esd.whs.mil/Directives/forms/dd1500_1999/',
  'https://www.esd.whs.mil/Directives/forms/dd2000_2499/',
  'https://www.esd.whs.mil/Directives/forms/dd2500_2999/',
  'https://www.esd.whs.mil/Directives/forms/dd3000_3499/'
];
const OUTPUT_FILE = join(__dirname, '../lib/dd-forms-data.js');
const SHRINK_TOLERANCE = 0.8;

const BROWSER_HEADERS = {
  'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36',
  'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,image/avif,image/webp,*/*;q=0.8',
  'Accept-Language': 'en-US,en;q=0.9',
  'Upgrade-Insecure-Requests': '1',
  'Sec-Fetch-Dest': 'document',
  'Sec-Fetch-Mode': 'navigate',
  'Sec-Fetch-Site': 'none'
};

async function fetchPage(url) {
  const response = await fetch(url, { headers: BROWSER_HEADERS });
  if (!response.ok) {
    throw new Error(`HTTP ${response.status} for ${url}`);
  }
  return response.text();
}

const clean = text => (text || '').replace(/\s+/g, ' ').trim();

/**
 * Ported from parseDodFormsTable in app.js. Rows are table body rows with at
 * least five cells: Number, Title, Edition Date, Controlled, OPR. The form
 * link is the first anchor in the row, resolved against the page it came
 * from.
 */
export function parseDdForms($, pageUrl) {
  const forms = [];
  $('table tbody tr').each((_, tr) => {
    const cells = $(tr).find('td');
    if (cells.length < 5) { return; }

    const number = clean(cells.eq(0).text());
    if (!number) { return; }

    const anchor = $(tr).find('a[href]').first();
    let link = pageUrl;
    if (anchor.length) {
      try { link = new URL(clean(anchor.attr('href')), pageUrl).href; } catch { link = pageUrl; }
    }

    forms.push({
      id: number,
      title: clean(cells.eq(1).text()),
      edition: clean(cells.eq(2).text()),
      controlled: clean(cells.eq(3).text()),
      opr: clean(cells.eq(4).text()),
      link,
      sourcePage: pageUrl
    });
  });
  return forms;
}

export function dedupeAndSort(forms) {
  const seen = new Set();
  const unique = [];
  for (const form of forms) {
    if (seen.has(form.id)) { continue; }
    seen.add(form.id);
    unique.push(form);
  }
  unique.sort((a, b) => {
    const numA = parseInt(a.id.replace(/\D/g, ''), 10) || 0;
    const numB = parseInt(b.id.replace(/\D/g, ''), 10) || 0;
    return numA - numB || a.id.localeCompare(b.id);
  });
  return unique;
}

async function existingRecordCount() {
  try {
    const current = await readFile(OUTPUT_FILE, 'utf-8');
    const match = current.match(/totalRecords:\s*(\d+)/);
    return match ? Number(match[1]) : 0;
  } catch {
    return 0;
  }
}

export function renderDataFile(forms, now = new Date().toISOString()) {
  return `/**
 * DD Forms Data
 *
 * Auto-generated from the WHS Directives Division DD Forms listings
 * Source: ${SOURCE_URL} (seven number-range pages)
 * Generated: ${now}
 * Total Records: ${forms.length}
 *
 * This file is automatically generated by scripts/fetch-dd-forms.mjs
 * DO NOT EDIT MANUALLY
 */

// DD Form data structure
const DD_FORMS = ${JSON.stringify(forms, null, 2)};

const DD_FORMS_META = {
  sourceUrl: '${SOURCE_URL}',
  generatedAt: '${now}',
  totalRecords: ${forms.length},
  lastUpdate: '${now}'
};

// Export for use in application
if (typeof window !== 'undefined') {
  window.DD_FORMS = DD_FORMS;
  window.DD_FORMS_META = DD_FORMS_META;
}

// Also support module exports for testing
if (typeof module !== 'undefined' && module.exports) {
  module.exports = {
    DD_FORMS,
    DD_FORMS_META
  };
}
`;
}

async function main() {
  console.log('[DD Forms] Starting fetch process...');
  const cheerio = await import('cheerio');

  const collected = [];
  const failedPages = [];
  for (const url of PAGE_URLS) {
    try {
      console.log('[DD Forms] Fetching:', url);
      const html = await fetchPage(url);
      const rows = parseDdForms(cheerio.load(html), url);
      console.log(`[DD Forms]   ${rows.length} rows`);
      collected.push(...rows);
    } catch (error) {
      console.error(`[DD Forms]   failed: ${error.message}`);
      failedPages.push(url);
    }
    // Courtesy delay between pages.
    await new Promise(resolve => setTimeout(resolve, 400));
  }

  // A partial run (some pages down) would write a file missing whole number
  // ranges, and the shrink check below would then block the next good run
  // from looking suspicious in the other direction. Require every page.
  if (failedPages.length) {
    console.error(`[DD Forms] ${failedPages.length} of ${PAGE_URLS.length} pages failed. Existing data left untouched.`);
    console.error('[DD Forms] Run this from a workstation, not CI or a cloud container.');
    process.exit(1);
  }

  const forms = dedupeAndSort(collected);
  const previous = await existingRecordCount();

  if (forms.length === 0) {
    console.error('[DD Forms] Parsed zero forms. Existing data left untouched.');
    console.error('[DD Forms] The table markup likely changed. Check parseDdForms against a live page.');
    process.exit(1);
  }

  if (previous > 0 && forms.length < previous * SHRINK_TOLERANCE) {
    console.error(`[DD Forms] Parsed ${forms.length} forms against ${previous} committed.`);
    console.error('[DD Forms] That drop looks like a partial scrape. Existing data left untouched.');
    process.exit(1);
  }

  await writeFile(OUTPUT_FILE, renderDataFile(forms), 'utf-8');
  console.log(`[DD Forms] Data file written to: ${OUTPUT_FILE}`);
  console.log(`[DD Forms] Total records: ${forms.length}`);
  console.log('[DD Forms] Complete');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main();
}
